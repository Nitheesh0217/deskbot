// Compiles supabase/functions/deskbot-v5/zones.ts into web/zones.js (global DeskZones) so the dashboard and the edge function share ONE implementation.
// Usage: node scripts/build_web.mjs [--check]
import { build } from "esbuild";
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";
const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const TARGETS = [["zones", "DeskZones"], ["coverage_view", "DeskCoverage"]];
let stale = false;
for (const [name, global] of TARGETS) {
  const r = await build({ entryPoints: [join(root, `supabase/functions/deskbot-v5/${name}.ts`)], bundle: true, write: false, format: "iife", globalName: global, target: "es2020", legalComments: "none" });
  const out = `// GENERATED by scripts/build_web.mjs from supabase/functions/deskbot-v5/${name}.ts. Do not edit.\n` + r.outputFiles[0].text;
  const target = join(root, "web", `${name}.js`);
  if (process.argv.includes("--check")) { let cur = ""; try { cur = readFileSync(target, "utf8"); } catch { /* missing */ } if (cur !== out) { console.error(`web/${name}.js is stale: run node scripts/build_web.mjs`); stale = true; } else console.log(`web/${name}.js current`); }
  else { writeFileSync(target, out); console.log(`wrote web/${name}.js`, out.length, "bytes"); }
}
if (stale) process.exit(1);
