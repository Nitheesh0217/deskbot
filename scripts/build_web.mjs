// Compiles supabase/functions/deskbot-v5/zones.ts into web/zones.js (global DeskZones) so the dashboard and the edge function share ONE implementation.
// Usage: node scripts/build_web.mjs [--check]
import { build } from "esbuild";
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";
const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const r = await build({ entryPoints: [join(root, "supabase/functions/deskbot-v5/zones.ts")], bundle: true, write: false, format: "iife", globalName: "DeskZones", target: "es2020", legalComments: "none" });
const out = "// GENERATED by scripts/build_web.mjs from supabase/functions/deskbot-v5/zones.ts. Do not edit.\n" + r.outputFiles[0].text;
const target = join(root, "web", "zones.js");
if (process.argv.includes("--check")) { let cur = ""; try { cur = readFileSync(target, "utf8"); } catch { /* missing */ } if (cur !== out) { console.error("web/zones.js is stale: run node scripts/build_web.mjs"); process.exit(1); } console.log("web/zones.js current"); }
else { writeFileSync(target, out); console.log("wrote web/zones.js", out.length, "bytes"); }
