// Writes supabase/functions/deskbot-v5/build_info.ts: sha256 of every other source file + a combined hash.
// Usage: node scripts/gen_build_info.mjs [--check]   (--check exits 1 if the committed file is stale)
import { readFileSync, readdirSync, writeFileSync } from "node:fs";
import { createHash } from "node:crypto";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";
const dir = join(dirname(fileURLToPath(import.meta.url)), "..", "supabase", "functions", "deskbot-v5");
const sha = (b) => createHash("sha256").update(b).digest("hex");
const files = Object.fromEntries(readdirSync(dir).filter((f) => f.endsWith(".ts") && f !== "build_info.ts").sort().map((f) => [f, sha(readFileSync(join(dir, f)))]));
const sourceSha256 = sha(Object.entries(files).map(([f, h]) => `${f}:${h}`).join("\n"));
const engineVersion = /export const VERSION = "([^"]+)"/.exec(readFileSync(join(dir, "engine.ts"), "utf8"))[1];
const out = `// GENERATED by scripts/gen_build_info.mjs — do not edit. Hashes the other source files in this directory.\nexport const BUILD = ${JSON.stringify({ engineVersion, sourceSha256, files }, null, 2)} as const;\n`;
const target = join(dir, "build_info.ts");
if (process.argv.includes("--check")) { let cur = ""; try { cur = readFileSync(target, "utf8"); } catch { /* missing */ } if (cur !== out) { console.error("build_info.ts is stale: run node scripts/gen_build_info.mjs"); process.exit(1); } console.log("build_info.ts current", sourceSha256); }
else { writeFileSync(target, out); console.log("wrote build_info.ts", sourceSha256); }
