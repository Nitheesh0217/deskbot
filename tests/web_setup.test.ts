import { test } from "node:test";
import assert from "node:assert/strict";
import vm from "node:vm";
import { readFileSync } from "node:fs";
import { build } from "esbuild";

const win: any = {}; vm.runInNewContext(readFileSync(new URL("../web/setup.js", import.meta.url), "utf8"), { window: win });
const S = win.DeskSetup;
const pal = { bull: "#4fd1c5", bear: "#d46bd6", obBull: "#5aa9e6", obBear: "#f2a93b", sl: "#f0616d", tp: "#3fcf8e", slText: "#f0616d", tpText: "#3fcf8e", fg: "#ffffff", muted: "#999999" };
const snap = (t: number) => t;
const long = { dir: "long", entry: 100, stop0: 99, stop: 99, tp1: 101, tp2: 102, tp3: 103, openT: 5000, tp1Done: false, tp2Done: false, tp3Done: false };
const short = { dir: "short", entry: 100, stop0: 101, stop: 101, tp1: 99, tp2: 98, tp3: 97, openT: 5000 };

test("trade boxes: red from entry to the ORIGINAL stop, three contiguous green blocks to TP3, both directions", () => {
  for (const [p, up] of [[long, true], [short, false]] as const) {
    const [sl, a, b, c] = S.tradeBoxes(p, pal, snap);
    assert.equal(sl.fill.startsWith("rgba(240,97,109"), true, "stop is red"); assert.equal(sl.line, "#f0616d");
    assert.equal(Math.max(sl.top, sl.bot), up ? 100 : 101); assert.equal(Math.min(sl.top, sl.bot), up ? 99 : 100);
    for (const g of [a, b, c]) { assert.equal(g.line, "#3fcf8e"); assert.ok(g.fill.startsWith("rgba(63,207,142")); }
    assert.equal(a.label, "TP1 +1.00R"); assert.equal(c.label, "TP3 +3.00R");
    const span = (x: any) => [Math.min(x.top, x.bot), Math.max(x.top, x.bot)];
    assert.deepEqual([span(a), span(b), span(c)], up ? [[100, 101], [101, 102], [102, 103]] : [[99, 100], [98, 99], [97, 98]]);
    assert.equal(sl.t1, 5000);
  }
});

test("a moved stop never rewrites the red block; hit targets are marked", () => {
  const boxes = S.tradeBoxes({ ...long, stop: 100, tp1Done: true }, pal, snap);
  assert.equal(Math.min(boxes[0].top, boxes[0].bot), 99, "red block still uses original stop");
  assert.match(boxes[1].label, /✓ hit/);
});

test("setup SVG draws red stop and green target blocks, escapes text and reports a moved stop", () => {
  const svg = S.setupSVG({ ...long, stop: 100, tp1Done: true }, pal, (x: number) => `<${x}>`);
  assert.ok((svg.match(/stroke="#f0616d"/g) || []).length >= 2); assert.ok((svg.match(/stroke="#3fcf8e"/g) || []).length >= 3);
  assert.ok(!svg.includes("<100>") && svg.includes("&lt;100&gt;"), "labels are escaped"); assert.match(svg, /stop moved/); assert.match(svg, /TP1 ✓/);
});

test("zone boxes follow layer toggles, label only the nearest few, and never emit probabilities", () => {
  const z = (i: number, kind: string, side: string) => ({ kind, side, top: 100 + i, bot: 99.5 + i, t0: 1, touched: i % 2 === 0, filled: 0.5, label: `${side} ${kind}` });
  const read = { price: 100, atr: 1, zones: [z(0, "FVG", "bull"), z(1, "IFVG", "bear"), z(2, "OB", "bull"), z(3, "FVG", "bear"), z(4, "FVG", "bull"), z(5, "FVG", "bull"), z(6, "OB", "bear")] };
  const all = S.zoneBoxes(read, { FVG: true, IFVG: true, OB: true }, pal, snap, 0);
  assert.equal(all.length, 7); assert.equal(all.filter((b: any) => b.label).length, 5); assert.ok(all.find((b: any) => b.dash), "IFVG dashed");
  assert.equal(S.zoneBoxes(read, { FVG: true }, pal, snap, 0).length, 4);
  assert.equal(S.zoneBoxes({ ...read, zones: [z(40, "FVG", "bull")] }, { FVG: true }, pal, snap, 0).length, 0, "far zones are dropped");
  assert.ok(!JSON.stringify(all).toLowerCase().includes("probab"));
});

test("web/zones.js is exactly the compilation of zones.ts (one implementation)", async () => {
  const r = await build({ entryPoints: [new URL("../supabase/functions/deskbot-v5/zones.ts", import.meta.url).pathname], bundle: true, write: false, format: "iife", globalName: "DeskZones", target: "es2020", legalComments: "none" });
  const expected = "// GENERATED by scripts/build_web.mjs from supabase/functions/deskbot-v5/zones.ts. Do not edit.\n" + r.outputFiles[0].text;
  assert.equal(readFileSync(new URL("../web/zones.js", import.meta.url), "utf8"), expected, "stale: run npm run build:web");
});
